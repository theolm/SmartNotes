"""Generate Android vectors from the existing masked SVG (no rasterization).

Install development-only dependencies:
  python3 -m pip install skia-pathops==0.8.0.post2 fonttools==4.60.2
Run from any directory: python3 app/tool/generate_android_icon.py
"""
from pathlib import Path
import xml.etree.ElementTree as ET

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path

APP = Path(__file__).resolve().parents[1]
RES = APP / "android/app/src/main/res"
NS = {"s": "http://www.w3.org/2000/svg"}


def circle(element):
    x, y, r = (float(element.attrib[k]) for k in ("cx", "cy", "r"))
    result = pathops.Path()
    parse_path(f"M{x-r},{y} A{r},{r} 0 1 0 {x+r},{y} A{r},{r} 0 1 0 {x-r},{y} Z", result.getPen())
    return result


def seal():
    root = ET.parse(APP / "assets/app_icon_foreground.svg").getroot()
    mask = root.find("s:defs/s:mask", NS)
    group = mask.find("s:g", NS)
    # Fail explicitly if the source changes beyond this converter's contract.
    assert group.attrib["transform"] == "translate(512 512) scale(0.7) translate(-512 -512)"
    cutouts = pathops.Path()
    for element in group:
        if element.tag.endswith("circle"):
            shape = circle(element)
        else:
            assert element.tag.endswith("path")
            shape = pathops.Path()
            parse_path(element.attrib["d"], shape.getPen())
            shape.stroke(float(group.attrib["stroke-width"]), pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
            shape.convertConicsToQuads()
        cutouts = pathops.op(cutouts, shape, pathops.PathOp.UNION)
    cutouts = cutouts.transform(0.7, 0, 0, 0.7, 153.6, 153.6)
    result = pathops.op(circle(mask.find("s:circle", NS)), cutouts, pathops.PathOp.DIFFERENCE)
    pen = SVGPathPen(None, ntos=lambda value: f"{value:.5f}".rstrip("0").rstrip("."))
    result.draw(pen)
    return pen.getCommands()


def main():
    data = seal()
    # The same transparent seal is used by adaptive, themed and splash icons.
    # 292/1024 fits both the Android 66/108 and splash 2/3 safe diameters.
    for name, size in [("smartnotes_foreground", 108), ("smartnotes_splash", 288)]:
        target = RES / "drawable-anydpi" / f"{name}.xml"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_icon.py; transparent quote cutouts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="1024" android:viewportHeight="1024">
    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"
        android:pathData="{data}" />
</vector>
''')


if __name__ == "__main__":
    main()
